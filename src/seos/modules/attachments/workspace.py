class Workspace:

    def radius(

        self,

        boom,

        dipper,

        bucket

    ):

        return boom+dipper+bucket


    def digging_depth(

        self,

        boom,

        dipper

    ):

        return boom*0.55+dipper*0.80


    def dumping_height(

        self,

        boom,

        dipper

    ):

        return boom*0.65+dipper*0.60
